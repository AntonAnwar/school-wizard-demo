def set_bidi(p):
    pPr = p._p.get_or_add_pPr()
    el = OxmlElement('w:bidi'); el.set(qn('w:val'), '1'); pPr.append(el)

def style_run(r, size=11, bold=False, color=None, mono=False, italic=False):
    f = 'Courier New' if mono else 'Arial'
    r.font.size = Pt(size); r.font.bold = bold; r.font.italic = italic
    r.font.name = f
    r._element.rPr.rFonts.set(qn('w:cs'), f)
    if color is not None:
        r.font.color.rgb = color

AL = {'right': WD_ALIGN_PARAGRAPH.RIGHT, 'center': WD_ALIGN_PARAGRAPH.CENTER,
      'left': WD_ALIGN_PARAGRAPH.LEFT, 'justify': WD_ALIGN_PARAGRAPH.JUSTIFY}

def add_p(text, size=11, bold=False, align='right', color=None, after=6, before=0, mono=False, bidi=True):
    p = doc.add_paragraph()
    if bidi: set_bidi(p)
    p.alignment = AL[align]
    r = p.add_run(text); style_run(r, size, bold, color, mono=mono)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    return p

def add_rich(segments, align='right', after=6, before=0, size=11):
    """segments: list of (text, {bold, color, mono})"""
    p = doc.add_paragraph(); set_bidi(p); p.alignment = AL[align]
    for t, o in segments:
        r = p.add_run(t); style_run(r, o.get('size', size), o.get('bold', False), o.get('color'), o.get('mono', False))
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    return p

def heading(num, text, level=1):
    p = doc.add_paragraph()
    set_bidi(p)
    p.alignment = AL['right']
    sizes = {1: 17, 2: 14, 3: 12.5}
    r = p.add_run(f"{num}  {text}" if num else text)
    style_run(r, sizes[level], True, INDIGO if level < 3 else DARK)
    p.paragraph_format.space_before = Pt(16 if level == 1 else 10)
    p.paragraph_format.space_after = Pt(6)
    if level == 1:
        pPr = p._p.get_or_add_pPr()
        pbdr = OxmlElement('w:pBdr')
        b = OxmlElement('w:bottom')
        b.set(qn('w:val'), 'single'); b.set(qn('w:sz'), '8'); b.set(qn('w:color'), '4338CA')
        pbdr.append(b); pPr.append(pbdr)
    return p

def _add_code_runs(p, text, size=11, color=DARK):
    import re
    for part in re.split(r'(<c>.*?</c>|<c>[^<]*)', text):
        if not part:
            continue
        if part.startswith('<c>'):
            r = p.add_run(part[3:].removesuffix('</c>') if part.endswith('</c>') else part[3:])
            style_run(r, size, False, RGBColor(0x37, 0x41, 0x51), mono=True)
        else:
            r = p.add_run(part); style_run(r, size, False, color)

def numbered_item(num, text):
    p = doc.add_paragraph()
    set_bidi(p); p.alignment = AL['right']
    r = p.add_run(f"{num}.  "); style_run(r, 11, True, INDIGO)
    _add_code_runs(p, text)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.right_indent = Inches(0.0)
    return p

def bullet(text, bold_head=None, after=3):
    p = doc.add_paragraph(style='List Bullet')
    set_bidi(p); p.alignment = AL['right']
    if bold_head:
        r = p.add_run(bold_head); style_run(r, 11, True, DARK)
    _add_code_runs(p, text)
    p.paragraph_format.space_after = Pt(after)
    return p

def numbered(text, bold_head=None):
    p = doc.add_paragraph(style='List Number')
    set_bidi(p); p.alignment = AL['right']
    if bold_head:
        r = p.add_run(bold_head); style_run(r, 11, True, DARK)
    r = p.add_run(text); style_run(r, 11, False, DARK)
    p.paragraph_format.space_after = Pt(3)
    return p

def shade(cell, fill):
    shd = OxmlElement('w:shd'); shd.set(qn('w:val'), 'clear'); shd.set(qn('w:fill'), fill)
    cell._tc.get_or_add_tcPr().append(shd)

def cell_text(cell, text, bold=False, size=10, align='right', mono=False, color=None, fill=None):
    cell.text = ''
    p = cell.paragraphs[0]
    is_code = mono
    if not is_code: set_bidi(p)
    p.alignment = AL[align]
    r = p.add_run(text); style_run(r, size, bold, color, mono=mono)
    p.paragraph_format.space_after = Pt(2); p.paragraph_format.space_before = Pt(2)
    if fill: shade(cell, fill)

def add_table(headers, rows, header_fill='4338CA', zebra=True, first_code=False):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.autofit = True
    for i, h in enumerate(headers):
        cell_text(t.rows[0].cells[i], h, bold=True, size=10, color=WHITE, fill=header_fill,
                  align='left' if h.startswith('<') else 'right')
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        fill = 'F4F6FB' if (zebra and ri % 2 == 1) else None
        for i, val in enumerate(row):
            mono = val.startswith('<c>')
            txt = val[3:] if mono else val
            if mono:
                cell_text(cells[i], txt, size=9.5, align='left', mono=True, color=RGBColor(0x37,0x41,0x51), fill=fill)
            else:
                cell_text(cells[i], txt, size=10, align='right', fill=fill)
    return t

def code_block(text):
    for line in text.split('\n'):
        p = doc.add_paragraph()
        p.alignment = AL['left']
        r = p.add_run(line if line else ' ')
        style_run(r, 9.5, False, RGBColor(0x1F, 0x29, 0x37), mono=True)
        pPr = p._p.get_or_add_pPr()
        shd = OxmlElement('w:shd'); shd.set(qn('w:val'), 'clear'); shd.set(qn('w:fill'), 'F3F4F6')
        pPr.append(shd)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.1
    sp = doc.add_paragraph(); sp.paragraph_format.space_after = Pt(6)

def page_break():
    doc.add_page_break()

